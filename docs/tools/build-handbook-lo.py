"""
Build the Lao user handbook (.docx) for the Land Tax Collection System.

Fonts: Saysettha OT for Lao (complex script), Times New Roman for Latin/digits.
Every run gets w:rFonts ascii/hAnsi/cs/eastAsia + w:szCs so Lao renders on a
machine where the Latin font lacks Lao glyphs.
"""
import copy
from docx import Document
from docx.shared import Pt, Cm, RGBColor
from docx.enum.text import WD_ALIGN_PARAGRAPH, WD_BREAK
from docx.enum.table import WD_TABLE_ALIGNMENT
from docx.enum.section import WD_SECTION
from docx.oxml.ns import qn
from docx.oxml import OxmlElement

LAO = "Saysettha OT"
LAT = "Times New Roman"

GREEN = RGBColor(0x1B, 0x5E, 0x20)
GREY = RGBColor(0x55, 0x55, 0x55)


# ---------------------------------------------------------------- helpers
def rfonts(el, latin=LAT, lao=LAO):
    """Force latin + complex-script + east-asian fonts on a rPr/ppr owner."""
    rPr = el.get_or_add_rPr() if hasattr(el, "get_or_add_rPr") else el
    rf = rPr.find(qn("w:rFonts"))
    if rf is None:
        rf = OxmlElement("w:rFonts")
        rPr.insert(0, rf)
    rf.set(qn("w:ascii"), latin)
    rf.set(qn("w:hAnsi"), latin)
    rf.set(qn("w:cs"), lao)
    rf.set(qn("w:eastAsia"), lao)


def sizes(el, pt, pt_cs=None):
    rPr = el.get_or_add_rPr() if hasattr(el, "get_or_add_rPr") else el
    for tag, val in (("w:sz", pt), ("w:szCs", pt_cs or pt + 1)):
        e = rPr.find(qn(tag))
        if e is None:
            e = OxmlElement(tag)
            rPr.append(e)
        e.set(qn("w:val"), str(int(val * 2)))


def bcs(run):
    """Bold must also be set for complex scripts, or Lao stays regular."""
    if run.bold:
        rPr = run._element.get_or_add_rPr()
        b = OxmlElement("w:bCs")
        rPr.append(b)


def style_font(style, size, bold=False, color=None):
    style.font.name = LAT
    style.font.size = Pt(size)
    style.font.bold = bold
    if color is not None:
        style.font.color.rgb = color
    rfonts(style.element)
    sizes(style.element, size, size + 1)
    if bold:
        rPr = style.element.get_or_add_rPr()
        b = OxmlElement("w:bCs")
        rPr.append(b)


def fin(doc, path):
    """Final pass: every run in the document gets the Lao-capable fonts."""
    body = doc.element.body
    for r in body.iter(qn("w:r")):
        rPr = r.find(qn("w:rPr"))
        if rPr is None:
            rPr = OxmlElement("w:rPr")
            r.insert(0, rPr)
        rf = rPr.find(qn("w:rFonts"))
        if rf is None:
            rf = OxmlElement("w:rFonts")
            rPr.insert(0, rf)
        rf.set(qn("w:cs"), LAO)
        rf.set(qn("w:eastAsia"), LAO)
        if rf.get(qn("w:ascii")) is None:
            rf.set(qn("w:ascii"), LAT)
            rf.set(qn("w:hAnsi"), LAT)
        if r.find(qn("w:rPr")).find(qn("w:b")) is not None:
            if rPr.find(qn("w:bCs")) is None:
                rPr.append(OxmlElement("w:bCs"))
    doc.save(path)


def H(doc, text, level=1):
    p = doc.add_heading(text, level=level)
    for r in p.runs:
        bcs(r)
    return p


def P(doc, text, bold=False, italic=False, size=None, align=None, space_after=6):
    p = doc.add_paragraph()
    r = p.add_run(text)
    r.bold = bold
    r.italic = italic
    if size:
        r.font.size = Pt(size)
    bcs(r)
    if align:
        p.alignment = align
    p.paragraph_format.space_after = Pt(space_after)
    return p


def B(doc, text, bold_prefix=None):
    """Bullet: optional bold lead-in followed by normal text."""
    p = doc.add_paragraph(style="List Bullet")
    if bold_prefix:
        r = p.add_run(bold_prefix)
        r.bold = True
        bcs(r)
    r2 = p.add_run(text)
    p.paragraph_format.space_after = Pt(3)
    return p


def N(doc, text):
    p = doc.add_paragraph(style="List Number")
    p.add_run(text)
    p.paragraph_format.space_after = Pt(3)
    return p


def CODE(doc, text):
    p = doc.add_paragraph()
    r = p.add_run(text)
    r.font.name = "Consolas"
    r.font.size = Pt(9.5)
    p.paragraph_format.left_indent = Cm(0.8)
    p.paragraph_format.space_before = Pt(3)
    p.paragraph_format.space_after = Pt(6)
    return p


def NOTE(doc, text):
    """Boxed callout: shaded paragraph with a left bar."""
    p = doc.add_paragraph()
    r = p.add_run(text)
    r.font.size = Pt(10.5)
    pRPr = p._p.get_or_add_pPr()
    shd = OxmlElement("w:shd")
    shd.set(qn("w:val"), "clear")
    shd.set(qn("w:fill"), "EEF3EA")
    pRPr.append(shd)
    bdr = OxmlElement("w:pBdr")
    left = OxmlElement("w:left")
    left.set(qn("w:val"), "single")
    left.set(qn("w:sz"), "18")
    left.set(qn("w:space"), "6")
    left.set(qn("w:color"), "1B5E20")
    bdr.append(left)
    pRPr.append(bdr)
    p.paragraph_format.left_indent = Cm(0.4)
    p.paragraph_format.right_indent = Cm(0.2)
    p.paragraph_format.space_before = Pt(4)
    p.paragraph_format.space_after = Pt(8)
    return p


def TABLE(doc, header, rows, widths=None):
    t = doc.add_table(rows=1, cols=len(header))
    t.style = "Table Grid"
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    hdr = t.rows[0].cells
    for i, h in enumerate(header):
        hdr[i].text = ""
        p = hdr[i].paragraphs[0]
        r = p.add_run(h)
        r.bold = True
        r.font.size = Pt(9.5)
        bcs(r)
        shd = OxmlElement("w:shd")
        shd.set(qn("w:val"), "clear")
        shd.set(qn("w:fill"), "DCE8D5")
        hdr[i]._tc.get_or_add_tcPr().append(shd)
    for row in rows:
        cells = t.add_row().cells
        for i, v in enumerate(row):
            cells[i].text = ""
            p = cells[i].paragraphs[0]
            r = p.add_run(str(v))
            r.font.size = Pt(9.5)
            p.paragraph_format.space_after = Pt(1)
    if widths:
        for row in t.rows:
            for i, w in enumerate(widths):
                row.cells[i].width = Cm(w)

    # Repeat the header row when the table breaks across a page, and never
    # split a single row in half — both matter in an 18-page manual.
    for tr in t.rows:
        trPr = tr._tr.get_or_add_trPr()
        trPr.append(OxmlElement("w:cantSplit"))
    hdr_trPr = t.rows[0]._tr.get_or_add_trPr()
    hdr_trPr.append(OxmlElement("w:tblHeader"))

    doc.add_paragraph().paragraph_format.space_after = Pt(4)
    return t


def page_break(doc):
    doc.add_paragraph().add_run().add_break(WD_BREAK.PAGE)


def add_page_numbers(section):
    p = section.footer.paragraphs[0]
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r = p.add_run()
    fld = OxmlElement("w:fldSimple")
    fld.set(qn("w:instr"), "PAGE")
    r._element.addnext(fld)
    p.add_run("  /  ")
    r2 = p.add_run()
    fld2 = OxmlElement("w:fldSimple")
    fld2.set(qn("w:instr"), "NUMPAGES")
    r2._element.addnext(fld2)
    for run in p.runs:
        run.font.size = Pt(9)
        rfonts(run._element)


